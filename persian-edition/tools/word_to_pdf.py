"""Update the automatic Word TOC and export that document through LibreOffice.

Uses a generated macro in a dedicated application profile. It does not change
macro security settings, embed a macro in the document, or use a remote service.
"""
import html
import json
import os
from pathlib import Path
import subprocess

EDITION=Path(__file__).resolve().parents[1]
ROOT=Path(os.environ.get('FA_LIBREOFFICE_ROOT','/workspace/libreoffice'))
PROGRAM=ROOT/'usr/lib/libreoffice/program'
PROFILE=Path(os.environ.get('FA_LIBREOFFICE_PROFILE','/workspace/lo-profile'))
MARKER='generated by persian-edition/tools/word_to_pdf.py'


def main():
    output=EDITION/'output/preview'
    docx=output/'Single_Cell_Best_Practices_FA_PREVIEW.docx'
    pdf=docx.with_suffix('.pdf')
    status=EDITION/'_build/toc-update.txt'
    status.unlink(missing_ok=True)
    basic=PROFILE/'user/basic'
    standard=basic/'Standard'
    standard.mkdir(parents=True,exist_ok=True)
    module=standard/'FA_Preview_Export.xba'
    if module.exists() and MARKER not in module.read_text():
        raise RuntimeError('Refusing to overwrite an existing user macro')
    code=f'''Sub Main
 Dim opts(0) As New com.sun.star.beans.PropertyValue
 opts(0).Name = "Hidden"
 opts(0).Value = True
 Dim doc As Object, indexes As Object, i As Integer
 doc = StarDesktop.loadComponentFromURL("{docx.as_uri()}", "_blank", 0, opts())
 indexes = doc.getDocumentIndexes()
 For i = 0 To indexes.getCount() - 1
  indexes.getByIndex(i).update()
 Next i
 doc.store()
 Dim exportOpts(0) As New com.sun.star.beans.PropertyValue
 exportOpts(0).Name = "FilterName"
 exportOpts(0).Value = "writer_pdf_Export"
 doc.storeToURL("{pdf.as_uri()}", exportOpts())
 Open "{status}" For Output As #1
 Print #1, indexes.getCount()
 Close #1
 doc.close(True)
 StarDesktop.terminate()
End Sub
'''
    module.write_text('<?xml version="1.0" encoding="UTF-8"?>\n<!-- '+MARKER+' -->\n<script:module xmlns:script="http://openoffice.org/2000/script" script:name="FA_Preview_Export" script:language="StarBasic">'+html.escape(code)+'</script:module>')
    xlc=basic/'script.xlc'
    if not xlc.exists():
        xlc.write_text('<?xml version="1.0"?><library:libraries xmlns:library="http://openoffice.org/2000/library"><library:library library:name="Standard" library:link="false"/></library:libraries>')
    index=standard/'script.xlb'
    if not index.exists():
        index.write_text('<?xml version="1.0"?><library:library xmlns:library="http://openoffice.org/2000/library" library:name="Standard" library:readonly="false" library:passwordprotected="false"></library:library>')
    content=index.read_text()
    if 'library:name="FA_Preview_Export"' not in content:
        if '</library:library>' not in content:raise ValueError('Unexpected Basic library configuration')
        index.write_text(content.replace('</library:library>','<library:element library:name="FA_Preview_Export"/></library:library>'))
    env=dict(os.environ)
    env['LD_LIBRARY_PATH']=str(PROGRAM)+':'+str(ROOT/'usr/lib/x86_64-linux-gnu')
    env['XDG_CACHE_HOME']='/workspace/lo-cache'
    env['XDG_CONFIG_HOME']='/workspace/lo-config'
    with (EDITION/'qa/libreoffice.log').open('w') as log:
        subprocess.run([str(PROGRAM/'soffice'),'--headless','--norestore',
            '-env:UserInstallation='+PROFILE.as_uri(),
            'macro:///Standard.FA_Preview_Export.Main'],env=env,stdout=log,stderr=log,check=True,timeout=120)
    toc_count=int(status.read_text().strip())
    if toc_count<1 or not pdf.exists():raise RuntimeError('PDF/TOC export did not complete')
    report={'preview_only':True,'updated_tables_of_contents':toc_count,
            'pdf':str(pdf.relative_to(EDITION)),'same_word_layout':True,'pdf_bytes':pdf.stat().st_size}
    (EDITION/'qa/WORD_PDF_CONVERSION.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n')
    print(json.dumps(report,ensure_ascii=False))


if __name__=='__main__':main()
